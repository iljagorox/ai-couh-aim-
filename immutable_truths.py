# -*- coding: utf-8 -*-
"""Короткие правила, которые добавляются в промпты агента и aim coach."""

_AGENT_TRUTHS = """
- Ты автономный агент: действуй последовательно и проверяй результат каждого шага.
- Верхние 200px экрана могут быть системной зоной Windows: не кликай там случайно.
- Если координаты элемента есть в UI TREE, используй центр прямоугольника [left,top,right,bottom].
- Если цель не уверенно распознана, сначала наведи курсор командой MOVE, прочитай hover/подсказку, потом кликай.
- Не повторяй одну и ту же команду больше двух раз. Меняй подход: соседний элемент, SCROLL, HOTKEY или SMART_EXPLORE.
- DONE используй только когда задача выполнена. Если не уверен, продолжай собирать контекст.
- Для сбора данных используй SEARCH, когда offline mode выключен.
- HOTKEY часто быстрее кликов: ctrl+l, ctrl+f, alt+tab, win+r, esc, enter.
- READ_FILE и LIST_DIR используй для файловой разведки, когда работаешь в browser/runtime режиме.
"""

_COACH_TRUTHS = """
- Давай один конкретный совет, который можно применить прямо сейчас.
- Не повторяй последние советы, если видишь ту же ошибку, уточняй действие.
- Учитывай игру: тактические шутеры требуют pre-aim и дисциплины остановки, тренажеры требуют чистой траектории и темпа.
- Если кадр неинформативный, честно скажи, что не видно, и дай короткий универсальный drill.
- В ответах на вопросы давай причину, действие и мини-дрилл на одну минуту.
"""


def get_agent_truths_text() -> str:
    return _AGENT_TRUTHS.strip()


def get_coach_truths_text() -> str:
    return _COACH_TRUTHS.strip()
